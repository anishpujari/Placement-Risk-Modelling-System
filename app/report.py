"""
PlacementAI - Printable risk card (PDF) for a single student or applicant.
Built with fpdf2's core fonts, so text is limited to Latin-1 ("Rs" stands in for the rupee sign).
"""

from datetime import date

from fpdf import FPDF

TEXT = (28, 36, 48)
MUTED = (91, 101, 115)
RULE = (221, 225, 230)
ACCENT = (31, 75, 122)
RISK_RGB = {"HIGH": (179, 38, 30), "MEDIUM": (183, 121, 31), "LOW": (47, 125, 87)}
RISK_LABEL = {"HIGH": "High", "MEDIUM": "Medium", "LOW": "Low"}


def _latin(text):
    """Make any string safe for the PDF core fonts."""
    text = str(text).replace("₹", "Rs ").replace("→", "->").replace("–", "-").replace("—", "-")
    return text.encode("latin-1", "replace").decode("latin-1")


class _Card(FPDF):
    def footer(self):
        self.set_y(-14)
        self.set_draw_color(*RULE)
        self.line(self.l_margin, self.get_y(), self.w - self.r_margin, self.get_y())
        self.ln(2)
        self.set_font("Helvetica", "", 7.5)
        self.set_text_color(*MUTED)
        self.cell(0, 4, _latin(
            f"Generated by PlacementAI on {date.today():%d %b %Y}. Risk intelligence only, not an automated "
            "credit decision (RBI Fair Practices Code)."
        ))
        self.cell(0, 4, f"Page {self.page_no()}", align="R")


def _heading(pdf, text):
    pdf.ln(3)
    pdf.set_font("Helvetica", "B", 10.5)
    pdf.set_text_color(*TEXT)
    pdf.cell(0, 6, _latin(text), new_x="LMARGIN", new_y="NEXT")
    pdf.set_draw_color(*RULE)
    pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
    pdf.ln(1.5)


def _rows(pdf, rows, x=None, width=None, value_colors=None):
    """Label/value rows; value_colors maps row index to an RGB tuple."""
    x = pdf.l_margin if x is None else x
    width = pdf.epw if width is None else width
    for i, (label, value) in enumerate(rows):
        pdf.set_x(x)
        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(*TEXT)
        pdf.cell(width * 0.62, 5.6, _latin(label))
        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(*((value_colors or {}).get(i, TEXT)))
        pdf.cell(width * 0.38, 5.6, _latin(value), align="R", new_x="LMARGIN", new_y="NEXT")


def _two_columns(pdf, left_title, left_rows, right_title, right_rows, left_colors=None, right_colors=None):
    gap = 10
    col_w = (pdf.epw - gap) / 2
    top = pdf.get_y()

    pdf.set_y(top)
    _sub_heading(pdf, left_title, pdf.l_margin, col_w)
    _rows(pdf, left_rows, pdf.l_margin, col_w, left_colors)
    left_end = pdf.get_y()

    if not right_title:
        return
    pdf.set_y(top)
    _sub_heading(pdf, right_title, pdf.l_margin + col_w + gap, col_w)
    _rows(pdf, right_rows, pdf.l_margin + col_w + gap, col_w, right_colors)
    pdf.set_y(max(left_end, pdf.get_y()))


def _sub_heading(pdf, text, x, width):
    pdf.ln(3)
    pdf.set_x(x)
    pdf.set_font("Helvetica", "B", 10.5)
    pdf.set_text_color(*TEXT)
    pdf.cell(width, 6, _latin(text), new_x="LMARGIN", new_y="NEXT")
    pdf.set_draw_color(*RULE)
    pdf.line(x, pdf.get_y(), x + width, pdf.get_y())
    pdf.ln(1.5)


def _drivers(pdf, contrib, top=10):
    """Table of the largest SHAP contributions with a small diverging bar per row."""
    top_df = contrib.head(top)
    max_abs = max(float(top_df["shap_high"].abs().max()), 1e-9)
    name_w, value_w, bar_w, pts_w = pdf.epw * 0.42, pdf.epw * 0.16, pdf.epw * 0.26, pdf.epw * 0.16

    pdf.set_font("Helvetica", "", 7.5)
    pdf.set_text_color(*MUTED)
    pdf.cell(name_w, 5, "Feature")
    pdf.cell(value_w, 5, "Value")
    pdf.cell(bar_w, 5, "Lowers risk  |  Raises risk", align="C")
    pdf.cell(pts_w, 5, "High-risk prob.", align="R", new_x="LMARGIN", new_y="NEXT")

    from model.shap_explainer import _format_value

    for r in top_df.itertuples():
        y = pdf.get_y()
        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(*TEXT)
        pdf.cell(name_w, 6, _latin(r.name))
        pdf.cell(value_w, 6, _latin(_format_value(r.value)))

        mid = pdf.get_x() + bar_w / 2
        length = abs(r.shap_high) / max_abs * (bar_w / 2 - 2)
        color = RISK_RGB["HIGH"] if r.shap_high > 0 else RISK_RGB["LOW"]
        pdf.set_fill_color(*color)
        x0 = mid if r.shap_high > 0 else mid - length
        pdf.rect(x0, y + 1.6, max(length, 0.4), 2.8, style="F")
        pdf.set_draw_color(*RULE)
        pdf.line(mid, y + 0.8, mid, y + 5.2)
        pdf.set_x(pdf.get_x() + bar_w)

        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(*color)
        pdf.cell(pts_w, 6, f"{r.effect_pp:+.1f} pts", align="R", new_x="LMARGIN", new_y="NEXT")

    rest = contrib.iloc[top:]
    if len(rest):
        pdf.set_font("Helvetica", "", 7.5)
        pdf.set_text_color(*MUTED)
        pdf.cell(0, 5, _latin(f"{len(rest)} other features contribute {rest['shap_high'].sum():+.2f} "
                              "in total (SHAP, log-odds)."), new_x="LMARGIN", new_y="NEXT")


def build_risk_card(*, record_id, title, meta, tier_label, tier, score_label, score_value,
                    facts, result, contrib, outcome=None, salary=None, actions=None):
    """
    Return the PDF as bytes.
    facts / outcome / salary: lists of (label, value) strings. result: predict_student() output.
    contrib: DataFrame from explain_full(). actions: list of strings.
    """
    pdf = _Card(format="A4")
    pdf.set_margins(18, 16, 18)
    pdf.set_auto_page_break(True, margin=18)
    pdf.add_page()

    # ── Header ──
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_text_color(*ACCENT)
    pdf.cell(0, 5, "PlacementAI  |  Placement risk card", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)

    top = pdf.get_y()
    pdf.set_font("Courier", "", 9)
    pdf.set_text_color(*MUTED)
    pdf.cell(0, 5, _latin(record_id), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(*TEXT)
    pdf.multi_cell(pdf.epw * 0.6, 7.5, _latin(title), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 9.5)
    pdf.set_text_color(*MUTED)
    pdf.multi_cell(pdf.epw * 0.6, 5, _latin(meta), new_x="LMARGIN", new_y="NEXT")
    bottom = pdf.get_y()

    tier = str(tier).upper()
    x_tier = pdf.l_margin + pdf.epw * 0.64
    x_score = pdf.l_margin + pdf.epw * 0.83
    for x, label, value, color in [
        (x_tier, tier_label, RISK_LABEL.get(tier, tier.title()), RISK_RGB.get(tier, TEXT)),
        (x_score, score_label, score_value, TEXT),
    ]:
        pdf.set_xy(x, top + 4)
        pdf.set_font("Helvetica", "", 8)
        pdf.set_text_color(*MUTED)
        pdf.cell(30, 5, _latin(label))
        pdf.set_xy(x, top + 9)
        pdf.set_font("Helvetica", "B", 15)
        pdf.set_text_color(*color)
        pdf.cell(30, 8, _latin(value))
        if label == tier_label:
            pdf.set_fill_color(*color)
            pdf.rect(x - 2.5, top + 9.5, 0.9, 7, style="F")

    pdf.set_y(max(bottom, top + 20) + 2)
    pdf.set_draw_color(*RULE)
    pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())

    # ── Facts and model view ──
    probs = result["class_probabilities"]
    model_rows = [
        ("Predicted tier", RISK_LABEL.get(result["risk_tier"], result["risk_tier"])),
        ("Probability of high risk", f"{probs.get('HIGH', 0) * 100:.1f}%"),
        ("Probability of medium risk", f"{probs.get('MEDIUM', 0) * 100:.1f}%"),
        ("Probability of low risk", f"{probs.get('LOW', 0) * 100:.1f}%"),
    ]
    _two_columns(pdf, "Profile and loan", facts, "Model assessment", model_rows,
                 right_colors={0: RISK_RGB.get(result["risk_tier"], TEXT)})

    # ── Drivers ──
    _heading(pdf, "What drives the high-risk probability (SHAP)")
    pdf.set_font("Helvetica", "", 7.5)
    pdf.set_text_color(*MUTED)
    pdf.multi_cell(0, 4, _latin(
        "Bars show each feature's SHAP contribution toward the high-risk class (log-odds). The right column "
        "shows how many points of high-risk probability the feature adds or removes. Probability effects are "
        "small when the model is already very confident."
    ), new_x="LMARGIN", new_y="NEXT")
    pdf.ln(1)
    _drivers(pdf, contrib)

    # ── Outcome / salary ──
    if outcome or salary:
        _two_columns(pdf, "Recorded placement outcome" if outcome else "Expected salary", outcome or salary,
                     "Salary" if outcome and salary else "", salary if outcome and salary else [])

    # ── Actions ──
    if actions:
        _heading(pdf, "Recommended actions")
        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(*TEXT)
        for a in actions:
            pdf.cell(5, 5.6, "-")
            pdf.multi_cell(0, 5.6, _latin(a), new_x="LMARGIN", new_y="NEXT")

    return bytes(pdf.output())
